const assert = require('node:assert/strict');
module.exports = async function labChecks(browser, base) {
  const page = await browser.newPage({viewport:{width:1400,height:1000}});
  const errors = [], external = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/*', route => {if (route.request().url().startsWith(base)) route.continue(); else {external.push(route.request().url()); route.abort();}});
  try {
    // A real chat turn is the input, and importing it must make no inference call.
    const conversation = await (await fetch(base+'/api/conversations',{method:'POST'})).json();
    const response = await fetch(base+`/api/conversations/${conversation.id}/chat`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({content:'Assess my saved answer from a real chat',model:'test:local'})});
    await response.text();
    const beforeUsage = await (await fetch(base+'/api/usage')).json();
    await page.goto(base+'/lab');
    await page.locator('#chat-source').waitFor();
    assert.equal(await page.locator('#chat-source-request').innerText(),'Assess my saved answer from a real chat');
    assert.match(await page.locator('#chat-turns [aria-current="true"]').innerText(),/Assess my saved answer/);
    await page.screenshot({path:'test-results/lab-report.png'});
    await page.goto(base+'/?conversation='+conversation.id);
    await page.locator('.message.assistant').waitFor();
    assert.equal(await page.locator('#messages a[href^="/lab"]').count(),0);
    assert.equal(await page.locator('#workspace a[href="/lab"]').count(),1);
    const saved = await (await fetch(base+`/api/conversations/${conversation.id}`)).json();
    await page.goto(base+`/lab?message=${saved.messages.at(-1).id}`);
    await page.waitForFunction(() => document.querySelector('#save-task').textContent.includes('Create experiment'));
    assert.equal(await page.locator('#chat-source-request').innerText(),'Assess my saved answer from a real chat');
    assert.equal(await page.locator('#chat-source-cost').innerText(),'$0 API charge');
    assert.match(await page.locator('#chat-source-runtime').innerText(),/runtime.*electricity unmeasured/);
    assert.match(await page.locator('#chat-source').innerText(),/Not rated yet/);
    assert.equal(await page.locator('#experiment-tools').evaluate(el => el.open),false);
    await page.locator('#chat-source summary').click();
    await page.locator('#start-review').click();
    assert.equal(await page.locator('#task-prompt').inputValue(),'Assess my saved answer from a real chat');
    assert.equal(await page.locator('#task-prompt').evaluate(el => el.readOnly),true);
    assert.match(await page.locator('#chat-source-info').innerText(),/Recorded message input/);
    await page.locator('#task-criteria').fill('Addresses the original request.\nContains no unsupported claims.');
    await page.locator('#rate-answer').click();
    await page.waitForFunction(() => document.querySelector('.lab-trial')?.textContent.includes('Saved chat answer'));
    assert.match(await page.locator('.lab-trial').innerText(),/Criteria were declared after this answer/);
    const afterUsage = await (await fetch(base+'/api/usage')).json();
    assert.equal(afterUsage.overview.requests,beforeUsage.overview.requests,'Import reuses the chat inference without adding usage');
    await page.locator('#chat-turns [aria-current="true"]').waitFor();
    await page.waitForFunction(() => !document.querySelector('#new-task').disabled);
    await page.locator('#new-task').click();
    await page.getByText('Optional manual examples',{exact:true}).click();
    await page.waitForFunction(() => document.querySelector('#lab-model').value === 'test:local');
    assert.equal(await page.locator('#run-original').isDisabled(), true);
    await page.locator('#example-math').click();
    await page.locator('#save-task').click();
    await page.waitForFunction(() => !document.querySelector('#run-original').disabled);
    await page.locator('#run-original').click();
    await page.waitForFunction(() => document.querySelectorAll('.lab-trial').length === 1 && document.querySelector('#stop-lab').hidden);
    const first = page.locator('.lab-trial').first();
    assert.match(await first.innerText(), /391/);
    assert.match(await first.innerText(), /Exact string check: matched/);
    assert.match(await first.innerText(), /Human verdict: not assessed/);
    await first.locator('summary').filter({hasText:'Assess this trial'}).click();
    const review = first.locator('.review-form');
    await review.locator('select').nth(0).selectOption('pass');
    await review.locator('select').nth(1).selectOption('pass');
    await review.locator('select').nth(2).selectOption('pass');
    await review.locator('textarea').fill('Verified arithmetic independently and checked number-only formatting.');
    await review.getByRole('button',{name:'Save assessment'}).click();
    await page.waitForFunction(() => document.querySelector('.lab-verdict').textContent === 'Human verdict: pass');
    await page.locator('#prepare-task').click();
    await page.getByRole('button',{name:'Use this draft',exact:true}).waitFor();
    assert.match(await page.locator('#preparation-result').innerText(), /The email body/);
    // Fake preparation is deliberately fallible. User reviews and replaces it.
    await page.getByRole('button',{name:'Use this draft',exact:true}).click();
    assert.equal(await page.locator('#run-prepared').isDisabled(), true);
    await page.locator('#prepared-prompt').fill('Calculate 17 times 23 and return only the number.');
    await page.locator('#added-context').fill('Use base-ten integer arithmetic.');
    await page.locator('#confirm-draft').check();
    await page.locator('#run-prepared').click();
    await page.waitForFunction(() => document.querySelectorAll('.lab-trial').length === 2 && document.querySelector('#stop-lab').hidden);
    assert.match(await page.locator('.lab-trial').first().innerText(), /Prepared \+ added context/);
    await page.locator('.lab-trial').first().getByText('Inspect exact inputs & criteria',{exact:true}).click();
    assert.match(await page.locator('.lab-trial').first().innerText(), /Use base-ten integer arithmetic/);
    const tid = await page.locator('#task-picker').inputValue();
    await page.reload();
    await page.getByText('Saved experiments',{exact:true}).click();
    await page.locator('#task-list button').filter({hasText:'Arithmetic sanity check'}).click();
    await page.waitForFunction(() => document.querySelectorAll('.lab-trial').length === 2);
    assert.match(await page.locator('#trial-history').innerText(), /Human verdict: pass/);
    await page.locator('#experiment-tools > summary').click();
    await page.locator('#task-prompt').fill('__lab_slow__');
    assert.equal(await page.locator('#run-original').isDisabled(), true);
    await page.locator('#save-task').click();
    await page.waitForFunction(() => !document.querySelector('#run-original').disabled);
    await page.locator('#run-original').click();
    await page.waitForFunction(() => document.querySelector('#live-output').textContent.includes('391'));
    await page.locator('#stop-lab').click();
    await page.waitForFunction(() => document.querySelector('#stop-lab').hidden);
    await page.waitForFunction(() => document.querySelector('.lab-trial')?.textContent.includes('cancelled'), null, {timeout:5000}).catch(async e => {console.log('Stop UI:', await page.locator('#lab-status').innerText()); console.log('Stop records:', await page.evaluate(async tid => (await (await fetch('/api/lab/tasks/'+tid)).json()).operations.map(o => ({status:o.status,error:o.error,kind:o.kind,revision:o.revision})),tid)); throw e;});
    assert.match(await page.locator('#history-count').innerText(), /3 trials/);
    // Mobile layout and saved experiment navigation remain available.
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.locator('#task-picker').isVisible(), true);
    await page.locator('#task-picker').selectOption(tid);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({path:'test-results/lab-mobile.png',fullPage:true});
    await page.setViewportSize({width:1400,height:1000});
    await page.locator('.lab-content').evaluate(el => el.scrollTop = 0);
    await page.screenshot({path:'test-results/lab-desktop.png',fullPage:true});
    assert.deepEqual(errors, []); assert.deepEqual(external, []);
    console.log('PASS: Lab task/create/save, original/prepared comparison, explicit draft approval, manual review, persistence, revisions, cancellation, desktop/mobile, no external requests');
  } finally {await page.close();}
};
